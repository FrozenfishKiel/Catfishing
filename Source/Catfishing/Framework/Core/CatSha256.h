#pragma once

#include "CoreMinimal.h"

/**
 * 项目内部的 SHA-256 基础实现，只负责"任意字节 → 32 字节摘要"这一件事。
 *
 * 这一层刻意不认识任何领域概念：不拼 canonical 文本、不挑字段、不写版本前缀，也不做十六进制或 Base64 格式化。
 * 领域编码是各系统自己的合同（Boundary 按固定字段顺序的 little-endian 字节流、媒体传输按分块规则拼出的载荷），
 * 把它们并进来只会让改一边静默改掉另一边的摘要。而 SHA-256 本身是 FIPS 180-4 定死的字节到字节映射，不带任何
 * 上下文，同一串输入字节在哪个领域都必须得到同一串输出，所以恰好只有这一层可以安全共用。
 *
 * 之前 Boundary hash 与媒体传输各自在匿名命名空间里维护了一份逐行相同的 SHA-256，和 CatFishingBoundaryHash.h
 * 里记录的 canonical 编码分叉属于同一类事故，这里按同样的处理方式收敛成唯一一份。
 */
namespace CatSha256
{
	/**
	 * 计算输入字节序列的 SHA-256 摘要。
	 * 返回固定 32 字节的原始摘要，字节顺序就是 SHA-256 标准输出顺序，可直接与外部工具的结果逐字节比较。
	 * 输入为空时返回空消息的标准摘要（e3b0c442...），不是空数组；需要十六进制或其他展示形式的调用方自行转换。
	 */
	TArray<uint8> Compute(const TArray<uint8>& Input);
}
